"""The CI gate detects stale revisions, drift and unsafe reuse on real PG."""
import os

import pytest
from alembic.util.exc import AutogenerateDiffsDetected
from alembic.config import Config
from sqlalchemy import text

from check_migrations import check_alignment, main, verify_clean_database
from pg_support import isolated_postgres


@pytest.fixture
def connection():
    if not os.environ.get('TEST_DATABASE_URL'):
        pytest.skip('Requires a disposable PostgreSQL test database')
    with isolated_postgres(os.environ['TEST_DATABASE_URL']) as engine:
        with engine.connect() as connection:
            yield connection


def config(connection):
    from pathlib import Path
    result = Config(str(Path(__file__).resolve().parents[1] / 'alembic.ini'))
    result.attributes['connection'] = connection
    return result


@pytest.mark.postgres
def test_clean_postgres_upgrades_and_matches_heads(connection):
    verify_clean_database(connection)


@pytest.mark.postgres
def test_gate_rejects_nonempty_database_without_modifying_it(connection):
    connection.execute(text('CREATE TABLE sentinel (id integer)'))
    connection.commit()
    with pytest.raises(RuntimeError, match='empty disposable database'):
        verify_clean_database(connection)
    assert connection.execute(text('SELECT count(*) FROM sentinel')).scalar_one() == 0


@pytest.mark.postgres
def test_gate_rejects_schema_drift_even_with_current_revision(connection):
    verify_clean_database(connection)
    connection.execute(text('ALTER TABLE universities ADD COLUMN ci_unexpected integer'))
    connection.commit()
    with pytest.raises(AutogenerateDiffsDetected):
        check_alignment(connection, config(connection))


@pytest.mark.postgres
def test_gate_rejects_missing_revision_even_when_schema_is_current(connection):
    verify_clean_database(connection)
    connection.execute(text('DELETE FROM alembic_version'))
    connection.commit()
    with pytest.raises(RuntimeError, match='Migration heads differ'):
        check_alignment(connection, config(connection))


@pytest.mark.parametrize('url', ['', 'sqlite:///admitflow_test_migrations', 'postgresql://localhost/production',
                                 'postgresql://localhost/admitflow_test',
                                 'postgresql://localhost/admitflow_test_migrations?options=-csearch_path=public'])
def test_cli_rejects_missing_unsafe_or_ambiguous_url_before_connecting(monkeypatch, url):
    monkeypatch.setenv('MIGRATION_DATABASE_URL', url)
    with pytest.raises(ValueError):
        main()
